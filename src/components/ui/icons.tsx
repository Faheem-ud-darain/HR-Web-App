// Every icon the app uses, tagged with its own name (data-icon="bell") so each one can have its own motion in
// globals.css ("Icon motion"). Import icons from here, never straight from @phosphor-icons/react/dist/ssr.
function named(name: string, Base: Icon): Icon {
  const Named = forwardRef<SVGSVGElement, IconProps>((props, ref) => <Base ref={ref} data-icon={name} {...props} />);
  Named.displayName = `Icon(${name})`;
  return Named;
}

